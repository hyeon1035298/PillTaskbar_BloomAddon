"""Reads an add-on's addon.conf, the one place its names are set, and writes what the
build needs from it.

  make-identity.py <addon.conf> <gen folder>
      gen/addon_identity.h  the C++ macros common/addon_protocol.h builds its names from
      gen/identity.json     the same values for make-manifest.py

addon.conf holds KEY="value" lines (the build script also sources it), # comments
and blank lines. Lists are space separated inside one value.
"""
import json
import os
import re
import sys

LINE = re.compile(r'^([A-Z][A-Z0-9_]*)="([^"\\$`]*)"\s*(#.*)?$')
REQUIRED = ["ADDON_ID", "ADDON_NAME", "ADDON_VERSION", "ADDON_MOD_SRC", "ADDON_WINDHAWK_MODS",
            "ADDON_SYMBOL_MODULES", "ADDON_NAME_KO", "ADDON_NAME_EN", "ADDON_LICENSE", "ADDON_MIN_BLOOM",
            "ADDON_THIRD_PARTY"]


def read_conf(path):
    conf = {}
    with open(path, encoding="utf-8") as f:
        for n, raw in enumerate(f, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            m = LINE.match(line)
            if not m:
                raise SystemExit(f'{path}:{n}: expected KEY="value"')
            if m.group(1) in conf:
                raise SystemExit(f"{path}:{n}: {m.group(1)} set twice")
            conf[m.group(1)] = m.group(2)
    missing = [k for k in REQUIRED if not conf.get(k)]
    if missing:
        raise SystemExit(f"{path}: missing {', '.join(missing)}")
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,63}", conf["ADDON_ID"]):
        raise SystemExit(f"{path}: ADDON_ID: lowercase letters, digits and '-'")
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]{0,40}", conf["ADDON_NAME"]):
        raise SystemExit(f"{path}: ADDON_NAME: letters and digits (it names files and objects)")
    return conf


def modules(conf):
    """[(file name, in the Client.Core package folder)] from 'a.dll b.dll:core'."""
    out = []
    for word in conf["ADDON_SYMBOL_MODULES"].split():
        name, _, where = word.partition(":")
        if where not in ("", "core") or not re.fullmatch(r"[\w.]+\.dll", name, re.I):
            raise SystemExit(f"ADDON_SYMBOL_MODULES: bad entry {word!r}")
        out.append((name, where == "core"))
    return out


def wide(text):
    return 'L"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_header(conf, path):
    mods = ", ".join(f"{{{wide(n)}, {'true' if core else 'false'}}}" for n, core in modules(conf))
    windhawk = ", ".join(wide(m) for m in conf["ADDON_WINDHAWK_MODS"].split())
    lines = [
        "// Generated by tools/make-identity.py from addon.conf. Do not edit.",
        "#pragma once",
        "",
        f"#define ADDON_ID {wide(conf['ADDON_ID'])}",
        f"#define ADDON_NAME {wide(conf['ADDON_NAME'])}",
        f"#define ADDON_VERSION {wide(conf['ADDON_VERSION'])}",
        f"#define ADDON_WINDHAWK_MODS {windhawk}",
        f"#define ADDON_SYMBOL_MODULES {mods}",
        "",
    ]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    conf_path, gen = sys.argv[1], sys.argv[2]
    conf = read_conf(conf_path)
    os.makedirs(gen, exist_ok=True)
    write_header(conf, os.path.join(gen, "addon_identity.h"))
    with open(os.path.join(gen, "identity.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(conf, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{conf['ADDON_ID']} {conf['ADDON_VERSION']} ({conf['ADDON_NAME']}) -> {gen}")


if __name__ == "__main__":
    main()
